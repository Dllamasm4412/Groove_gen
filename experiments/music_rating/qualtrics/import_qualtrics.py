"""
Import a Qualtrics CSV export of Experiment 1 (remote) into analysis tables.

Export from Qualtrics: Data & Analysis > Export & Import > Export Data > CSV.
Either "Use numeric values" or "Use choice text" works. The survey must be the one generated by build_qsf.py.

Usage (from the repository root):
    .venv/bin/python experiments/music_rating/qualtrics/import_qualtrics.py EXPORT.csv
writes study_data/music_rating_qualtrics/<export name>/ (gitignored):
    ratings_long.csv   one row per participant x main clip, joined with the
                       hidden stimulus manifest (cell, genre, tier, BPM, rung);
                       0-100 ratings plus the same on 0-5 (value / 20)
    participants.csv   one row per response with quality flags and a
                       suggested_include column (flags only; nothing is dropped).
                       Headphones: the headphone-check score if the survey had
                       one, otherwise the self-report (post_headphones = Yes).
    qc_summary.txt     counts and any data-integrity problems

Where the data come from:
    - each clip's play record: embedded data __js_t_<stimulus id>, written by
      the listening page (sid, position shown, plays, full play, timing);
    - the ratings: loop columns "<k>_dance_1", "<k>_calming_1", "<k>_rt_Page Submit".
Qualtrics numbers loop columns by the row of the Loop & Merge table
(--loop-prefix row, the default; row k = k-th ID of the sorted main IDs).
Confirm it once with a verification run (QUALTRICS_BUILD.md):
    import_qualtrics.py EXPORT.csv --verify RESPONSE_ID
where the tester set every dance slider to the clip number shown on screen.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parent
REPO = EXP.parent.parent
for p in (EXP, HERE):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import headphone_check as hc  # noqa: E402
import prepare_qualtrics as pq  # noqa: E402
import stimuli as st  # noqa: E402

OUT_ROOT = REPO / 'study_data' / 'music_rating_qualtrics'

DANCE, CALM, RT = 'dance', 'calming', 'rt'
HP_TAGS = [f'hp{i}' for i in range(1, 7)]
ATTN = 'attn'
PID = 'pid'
POST = ('post_headphones', 'post_volume', 'post_quiet', 'post_problems')
RECORD = '__js_t_'

# Quality thresholds (researcher decisions; flags only)
ATTN_MIN = 90                 # instructed: "move this slider all the way to the right"
STRAIGHTLINE_SD = 2.0         # both scales' SD below this across 27 clips
FULL_PLAY_TOLERANCE_S = 0.5   # played time may fall this short of the clip length

LOOP_COL = re.compile(r'^(\d+)_(dance|calming|rt)(?:_(?:\d+|Page Submit|First Click|Last Click|Click Count))?$')
NORMAL_STATUS = {'0', 'IP Address'}       # numeric or choice-text export; previews/tests/spam are other values
MOBILE = re.compile(r'Mobi|Android|iPhone|iPad', re.I)
HEADPHONES_YES = {'1', 'Yes'}  # post_headphones choice 1 = "Yes" (numeric or choice-text export)
FINISHED_YES = {'1', 'True', 'true'}


def read_export(path: Path) -> tuple[list[str], list[dict]]:
    """(header, rows) of a Qualtrics CSV export, without its two extra header rows."""
    with Path(path).open(newline='', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        header = list(reader.fieldnames or [])
    while rows and (rows[0].get('ResponseId', '').startswith('{') or rows[0].get('ResponseId') == 'Response ID'):
        rows.pop(0)
    return header, rows


def loop_columns(header: list[str]) -> dict[int, dict[str, str]]:
    """{loop prefix: {'dance'|'calming'|'rt': column}} (Page Submit for rt)."""
    out: dict[int, dict[str, str]] = {}
    for col in header:
        m = LOOP_COL.match(col)
        if not m:
            continue
        k, tag = int(m.group(1)), m.group(2)
        if tag == RT and not col.endswith('Page Submit'):
            continue
        out.setdefault(k, {})[tag] = col
    return out


def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _json(v):
    try:
        x = json.loads(v)
    except (TypeError, ValueError):
        return None
    return x if isinstance(x, dict) else None


def _first(row: dict, names: list[str]):
    for n in names:
        if row.get(n) not in (None, ''):
            return row[n]
    return None


def spearman(xs: list[float], ys: list[float]) -> float | None:
    n = len(xs)
    if n < 3:
        return None

    def ranks(v):
        r = [0.0] * n
        for pos, i in enumerate(sorted(range(n), key=lambda i: v[i])):
            r[i] = pos
        return r
    rx, ry = ranks(xs), ranks(ys)
    return 1 - 6 * sum((a - b) ** 2 for a, b in zip(rx, ry)) / (n * (n * n - 1))


def prefix_to_sid(prefix_mode: str, table: list[str], records: dict[str, dict]) -> dict[int, str]:
    if prefix_mode == 'row':
        return {k: sid for k, sid in enumerate(table, 1)}
    return {r['pos']: sid for sid, r in records.items() if isinstance(r.get('pos'), int)}


def import_rows(rows: list[dict], header: list[str], manifest: dict, hp_manifest: dict,
                prefix_mode: str = 'row') -> tuple[list, list, list]:
    """(long rows, participant rows, problems)."""
    stim = {s['stimulus_id']: s for s in st.by_kind(manifest, 'main')}
    table = pq.main_rows(manifest)
    cols = loop_columns(header)
    answers = {t['id']: t['answer'] for t in hp_manifest['trials']}
    has_hp_check = any(h in header for h in HP_TAGS)
    long_rows, people, problems = [], [], []
    for r in rows:
        rid = r.get('ResponseId', '')
        records = {sid: rec for sid in stim if (rec := _json(r.get(RECORD + sid))) is not None}
        for sid, rec in records.items():
            if rec.get('sid') != sid:
                problems.append(f'{rid}: record {RECORD}{sid} names clip {rec.get("sid")!r}')
        to_sid = prefix_to_sid(prefix_mode, table, records)
        trials = []
        for k in sorted(cols):
            c = cols[k]
            dance, calm = _num(r.get(c.get(DANCE, ''))), _num(r.get(c.get(CALM, '')))
            if dance is None and calm is None:
                continue
            sid = to_sid.get(k)
            if sid not in stim:
                problems.append(f'{rid} loop {k}: ratings without a known clip; skipped')
                continue
            rec, s = records.get(sid), stim[sid]
            if rec is None:
                problems.append(f'{rid} loop {k}: ratings for {sid} but no play record')
                rec = {}
            played = _num(rec.get('played_s'))
            trials.append({
                'response_id': rid, 'pid': r.get(PID, ''), 'loop_prefix': k, 'position': rec.get('pos'),
                'stimulus_id': sid, 'cell': s['cell'], 'genre': s['genre'], 'tier': s['tier'], 'bpm': s['bpm'],
                'rung': s['rung'], 'danceability': dance, 'calming': calm,
                'danceability_0_5': None if dance is None else dance / 20,
                'calming_0_5': None if calm is None else calm / 20,
                'plays': rec.get('plays'), 'prior_plays': rec.get('prior_plays'),
                'pauses': len(rec.get('pauses') or []), 'stalls': rec.get('stalls'),
                'played_s': played, 'clip_duration_s': s['duration_s'],
                'full_play': bool(rec.get('complete')) and played is not None
                and played >= s['duration_s'] - FULL_PLAY_TOLERANCE_S,
                'rate_page_s': _num(r.get(c.get(RT, ''))), 'audio_start': rec.get('start'), 'audio_end': rec.get('end'),
                'errors': ';'.join(rec.get('errors') or []),
            })
        sids = [t['stimulus_id'] for t in trials]
        rated = [t for t in trials if t['danceability'] is not None and t['calming'] is not None]
        by_pos = sorted((t for t in trials if isinstance(t['position'], int)), key=lambda t: t['position'])
        hp_correct = sum(_num(r.get(h)) == answers[h] for h in HP_TAGS if h in answers) if has_hp_check else None
        attn = _num(_first(r, [ATTN, f'{ATTN}_1']))
        device = _json(r.get('__js_device')) or {}

        def sd(key):
            return statistics.pstdev([t[key] for t in rated]) if len(rated) > 1 else None
        sd_d, sd_c = sd('danceability'), sd('calming')
        p = {
            'response_id': rid, 'pid': r.get(PID, ''), 'status': r.get('Status', ''),
            'finished': r.get('Finished', ''), 'duration_s': _num(r.get('Duration (in seconds)')),
            'start': r.get('StartDate', ''), 'n_rated': len(rated), 'n_play_records': len(records),
            'complete_27': len(rated) == len(stim) and set(sids) == set(stim) and len(set(sids)) == len(sids),
            'all_full_play': bool(trials) and all(t['full_play'] for t in trials),
            'n_replays': sum(max(0, (t['plays'] or 1) - 1) for t in trials),
            'headphone_correct': hp_correct,
            'headphone_pass': None if hp_correct is None else hp_correct >= hp_manifest['pass_min_correct'],
            'headphones_self_report': r.get('post_headphones', '').strip() in HEADPHONES_YES,
            'attention_value': attn, 'attention_pass': attn is not None and attn >= ATTN_MIN,
            'sd_danceability': None if sd_d is None else round(sd_d, 2),
            'sd_calming': None if sd_c is None else round(sd_c, 2),
            'straightline': sd_d is not None and sd_d < STRAIGHTLINE_SD and sd_c < STRAIGHTLINE_SD,
            'same_genre_adjacent': sum(a['genre'] == b['genre'] for a, b in zip(by_pos, by_pos[1:])),
            'order_ladder_rank_corr': None if len(by_pos) < 3 else round(
                spearman([t['position'] for t in by_pos], [t['rung'] for t in by_pos]), 3),
            'volume_plays': _num(r.get('__js_vol')), 'mobile': bool(MOBILE.search(device.get('ua', ''))),
            'browser': device.get('ua', ''), 'screen': device.get('screen'),
            **{q: r.get(q, '') for q in POST},
        }
        headphones_ok = p['headphone_pass'] if has_hp_check else p['headphones_self_report']
        p['suggested_include'] = (p['status'] in NORMAL_STATUS and p['finished'] in FINISHED_YES
                                  and p['complete_27'] and headphones_ok and p['attention_pass']
                                  and p['all_full_play'] and not p['straightline'] and not p['mobile'])
        people.append(p)
        long_rows.extend(trials)
    return long_rows, people, problems


def verify(rows: list[dict], header: list[str], manifest: dict, response_id: str) -> str:
    """For a test run where every dance slider was set to the clip number shown:
    which loop-column numbering makes dance == position for every clip?"""
    r = next((x for x in rows if x.get('ResponseId') == response_id), None)
    if r is None:
        raise SystemExit(f'no response {response_id} in the export')
    stim = {s['stimulus_id'] for s in st.by_kind(manifest, 'main')}
    records = {sid: rec for sid in stim if (rec := _json(r.get(RECORD + sid))) is not None}
    cols = loop_columns(header)
    out = [f'response {response_id}: {len(records)} play records, {len(cols)} loop columns']
    for mode in ('row', 'position'):
        to_sid = prefix_to_sid(mode, pq.main_rows(manifest), records)
        checks = [(_num(r.get(c.get(DANCE, ''))), records.get(to_sid.get(k), {}).get('pos')) for k, c in cols.items()]
        checks = [(d, p) for d, p in checks if d is not None]
        ok = sum(d == p for d, p in checks)
        out.append(f'  --loop-prefix {mode}: {ok}/{len(checks)} ratings match the clip number shown')
    return '\n'.join(out)


def _write(path: Path, rows: list[dict]) -> None:
    fields = list(dict.fromkeys(k for r in rows for k in r)) if rows else ['empty']
    with path.open('w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def summary(people: list[dict], long_rows: list[dict], problems: list[str], export: Path, sha: str,
            prefix_mode: str) -> str:
    def count(key):
        return sum(bool(p[key]) for p in people)
    lines = [f'export: {export}', f'stimulus manifest: {sha}', f'loop columns numbered by: {prefix_mode}',
             f'responses: {len(people)}',
             f'  normal (not preview/test): {sum(p["status"] in NORMAL_STATUS for p in people)}',
             f'  complete (27 rated): {count("complete_27")}', f'  headphone check pass: {count("headphone_pass")}',
             f'  headphones whole survey (self-report): {count("headphones_self_report")}',
             f'  attention pass: {count("attention_pass")}', f'  all clips fully played: {count("all_full_play")}',
             f'  straight-lining: {count("straightline")}', f'  mobile device: {count("mobile")}',
             f'  suggested include: {count("suggested_include")}',
             f'rating rows: {len(long_rows)}', f'integrity problems: {len(problems)}', *[f'  {x}' for x in problems]]
    return '\n'.join(lines) + '\n'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('export', type=Path)
    ap.add_argument('--out', type=Path, default=None)
    ap.add_argument('--stim-dir', type=Path, default=st.STIM_DIR)
    ap.add_argument('--hp-dir', type=Path, default=hc.OUT_DIR)
    ap.add_argument('--loop-prefix', choices=('row', 'position'), default='row')
    ap.add_argument('--verify', metavar='RESPONSE_ID', help='check a verification run and exit')
    ap.add_argument('--force', action='store_true', help='replace an existing output folder')
    args = ap.parse_args(argv)
    manifest, sha = st.load_manifest(args.stim_dir)
    hpm = hc.load_manifest(args.hp_dir)
    header, rows = read_export(args.export)
    if args.verify:
        print(verify(rows, header, manifest, args.verify))
        return 0
    out = args.out or OUT_ROOT / args.export.stem
    if out.exists() and any(out.iterdir()) and not args.force:
        raise SystemExit(f'{out} already exists; use --force to replace it')
    long_rows, people, problems = import_rows(rows, header, manifest, hpm, args.loop_prefix)
    out.mkdir(parents=True, exist_ok=True)
    _write(out / 'ratings_long.csv', long_rows)
    _write(out / 'participants.csv', people)
    text = summary(people, long_rows, problems, args.export, sha, args.loop_prefix)
    (out / 'qc_summary.txt').write_text(text, encoding='utf-8')
    print(text + f'wrote {out}')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
